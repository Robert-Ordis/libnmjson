/**
 *	\brief		double を JSON 数値文字列にする
 *	\arg		buf		: 出力先。NUMFMT_F64_MAX_バイト以上。'\0'終端はしない
 *	\arg		val		: 値。有限値であること
 *	\return		書き込んだ文字数。NaN/Infinityの場合は0(何も書かない。呼び出し側で処理する)
 *	\remarks	桁はRyuによる最短表現（読み戻すと必ず同じdoubleになる）。
 *				表記はECMAScript Number::toString準拠（JSON.stringifyと同一）:
 *					1e-7 <= |v| < 1e21 は固定小数点、それ以外は指数表記(例: 1e+21, 1.5e-7)
 *				ただし -0 のみ例外として "-0.0" を出力する（ECMAScriptは"0"。符号と浮動小数型を保つため）
 */
size_t nmjson_numfmt_f64_(char *buf, double val){
	const uint64_t bits = double_to_bits(val);
	const bool ieeeSign = ((bits >> (DOUBLE_MANTISSA_BITS + DOUBLE_EXPONENT_BITS)) & 1) != 0;
	const uint64_t ieeeMantissa = bits & ((1ull << DOUBLE_MANTISSA_BITS) - 1);
	const uint32_t ieeeExponent = (uint32_t) ((bits >> DOUBLE_MANTISSA_BITS) & ((1u << DOUBLE_EXPONENT_BITS) - 1));
	floating_decimal_64 v;
	char digits[17];
	uint32_t olength;
	int32_t n;
	int32_t i;
	size_t idx = 0;

	if(ieeeExponent == ((1u << DOUBLE_EXPONENT_BITS) - 1u)){
		return 0;
	}
	if(ieeeExponent == 0 && ieeeMantissa == 0){
		if(ieeeSign){
			memcpy(buf, "-0.0", 4);
			return 4;
		}
		buf[0] = '0';
		return 1;
	}

	if(d2d_small_int(ieeeMantissa, ieeeExponent, &v)){
		// upstreamのd2s_buffered_nと同様、末尾の0を指数側へ移す
		for(;;){
			const uint64_t q = div10(v.mantissa);
			const uint32_t r = ((uint32_t) v.mantissa) - 10 * ((uint32_t) q);
			if(r != 0){
				break;
			}
			v.mantissa = q;
			++v.exponent;
		}
	}
	else{
		v = d2d(ieeeMantissa, ieeeExponent);
	}

	// 桁を取り出す（v.mantissaは末尾0を含まない）
	olength = decimalLength17(v.mantissa);
	numfmt_u64_to_dec_(digits, v.mantissa);
	// 値 = 0.d1d2...dk × 10^n
	n = v.exponent + (int32_t)olength;

	if(ieeeSign){
		buf[idx++] = '-';
	}

	if((int32_t)olength <= n && n <= 21){
		// 整数: ddd000
		memcpy(&buf[idx], digits, olength); idx += olength;
		for(i = (int32_t)olength; i < n; i++){ buf[idx++] = '0'; }
	}
	else if(0 < n && n <= 21){
		// 小数: dd.ddd
		memcpy(&buf[idx], digits, (size_t)n); idx += (size_t)n;
		buf[idx++] = '.';
		memcpy(&buf[idx], &digits[n], olength - (uint32_t)n); idx += olength - (uint32_t)n;
	}
	else if(-6 < n && n <= 0){
		// 小さい小数: 0.000ddd
		buf[idx++] = '0';
		buf[idx++] = '.';
		for(i = n; i < 0; i++){ buf[idx++] = '0'; }
		memcpy(&buf[idx], digits, olength); idx += olength;
	}
	else{
		// 指数表記: d.ddde+XX
		int32_t e = n - 1;
		buf[idx++] = digits[0];
		if(olength > 1){
			buf[idx++] = '.';
			memcpy(&buf[idx], &digits[1], olength - 1); idx += olength - 1;
		}
		buf[idx++] = 'e';
		buf[idx++] = (e < 0) ? '-' : '+';
		idx += numfmt_u64_to_dec_(&buf[idx], (uint64_t)((e < 0) ? -e : e));
	}
	return idx;
}
